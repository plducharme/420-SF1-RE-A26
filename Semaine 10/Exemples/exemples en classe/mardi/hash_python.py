# Un hash est une fonction mathématique qui calcule une valeur unique pour ce qui est passé en paramètre
citation_a = "L'erreur est humaine, mais ça prend un ordi pour merder royalement!"
citation_b = "L'erreur est humaine, mais ça prend un ardi pour merder royalement!"

print(hash(citation_a))
print(hash(citation_b))

